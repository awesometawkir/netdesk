def available_presets(platforms):
    """Only expose presets defined for every platform in a mixed inventory."""
    platforms = list(dict.fromkeys(platforms))
    if not platforms:
        return []
    return [name for name in SCENARIOS if all(name in PRESETS[p] for p in platforms)]


def get_commands(platform, preset):
    try:
        return PRESETS[platform][preset][:]
    except KeyError as error:
        raise ValueError(f'Preset {preset!r} is not defined for {platform}. Choose a supported scenario or custom commands.') from error
